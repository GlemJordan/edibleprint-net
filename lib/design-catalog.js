import catalog from '../content/design-catalog.json';
import { CATALOG_PRICES } from './catalog-prices.js';

// Single source of truth for the ready-made design catalog. To add a new
// design: drop its PNG in public/designs/<category>/ and add an entry to
// content/design-catalog.json — no component needs to change. Validated
// once at import time so a malformed manifest entry (bad category, a shape
// that doesn't actually exist in CATALOG_PRICES) fails loudly here instead
// of silently breaking the catalog page or, worse, checkout.

const CATEGORY_IDS = new Set(catalog.categories.map((c) => c.id));
const seenIds = new Set();

for (const d of catalog.designs) {
  if (seenIds.has(d.id)) throw new Error(`[design-catalog] duplicate design id "${d.id}"`);
  seenIds.add(d.id);
  if (!CATEGORY_IDS.has(d.category)) {
    throw new Error(`[design-catalog] design "${d.id}" has unknown category "${d.category}"`);
  }
  if (!d.supportedShapes || d.supportedShapes.length === 0) {
    throw new Error(`[design-catalog] design "${d.id}" has no supportedShapes`);
  }
  for (const shape of d.supportedShapes) {
    if (!CATALOG_PRICES[shape]) {
      throw new Error(`[design-catalog] design "${d.id}" supports unknown shape "${shape}"`);
    }
  }
  if (!d.textZone || !d.textZone.position) {
    throw new Error(`[design-catalog] design "${d.id}" has no textZone`);
  }
  for (const [shape, o] of Object.entries(d.shapeOverrides || {})) {
    if (!d.supportedShapes.includes(shape)) {
      throw new Error(`[design-catalog] design "${d.id}" overrides shape "${shape}" it doesn't support`);
    }
    if (o.textZone && !o.textZone.position) {
      throw new Error(`[design-catalog] design "${d.id}" override "${shape}" has a textZone without position`);
    }
    checkPhotoZone(`design "${d.id}" override "${shape}"`, o.photoZone);
  }
  checkPhotoZone(`design "${d.id}"`, d.photoZone);
}

// photoZone (optional): the artwork's clear centre, where the customer's
// photo can go — a mask PNG (alpha = window) plus the window's bounding box
// in % of the artwork. Both are generated by scripts/build-photo-masks.py.
function checkPhotoZone(tag, z) {
  if (z == null) return;
  const b = z.box || {};
  const ok = typeof z.mask === 'string' && z.mask.startsWith('/')
    && ['x', 'y', 'w', 'h'].every((k) => typeof b[k] === 'number' && b[k] >= 0 && b[k] <= 100)
    && b.w > 0 && b.h > 0;
  if (!ok) throw new Error(`[design-catalog] ${tag} has an invalid photoZone`);
}

/**
 * The design as it should be drawn on a given shape. A design can ship a
 * separate artwork (and text zone) for a shape whose proportions differ —
 * e.g. a portrait A4 version for "fullsheet", so a square artwork isn't
 * cropped by the cover-fit. Falls back to the design's own sourceFile,
 * textZone and photoZone for every shape without an override.
 */
export function designForShape(design, shape) {
  const o = design?.shapeOverrides?.[shape];
  if (!o) return design;
  // A photo window belongs to one artwork: an override with its own artwork
  // only gets a photoZone if it ships one for that artwork.
  const photoZone = o.sourceFile ? o.photoZone : (o.photoZone || design.photoZone);
  return {
    ...design,
    sourceFile: o.sourceFile || design.sourceFile,
    textZone: o.textZone || design.textZone,
    photoZone: photoZone || undefined,
  };
}

/** True when the customer can add a photo to this design on this shape. */
export function supportsPhoto(design, shape) {
  return Boolean(designForShape(design, shape)?.photoZone);
}

export function getCategories() {
  return catalog.categories;
}

export function getActiveDesigns() {
  return catalog.designs.filter((d) => d.active !== false);
}

export function getDesignById(id) {
  return catalog.designs.find((d) => d.id === id && d.active !== false) || null;
}

export function searchDesigns({ query = '', categoryId = '' } = {}) {
  const q = query.trim().toLowerCase();
  return getActiveDesigns().filter((d) => {
    if (categoryId && d.category !== categoryId) return false;
    if (q && !d.name.toLowerCase().includes(q)) return false;
    return true;
  });
}
